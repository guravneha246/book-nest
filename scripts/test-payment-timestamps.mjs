import path from 'path';
import fetch from 'node-fetch';

// Enforce isolated test database BEFORE importing server/database modules
const testDbPath = process.env.DB_PATH || path.resolve(process.cwd(), 'data', 'booknest.test.db');
process.env.DB_PATH = testDbPath;
process.env.NODE_ENV = 'test';

const { app } = await import('../server/server.js');
const { db, closeDatabase } = await import('../server/database/index.js');
const { formatOrderDate } = await import('../server/controllers/ordersController.js');

const TEST_PORT = 5058;
const API_URL = `http://localhost:${TEST_PORT}/api`;
let server;

let passed = 0;
let failed = 0;

function assert(condition, message) {
  if (condition) {
    console.log(`  ✅ PASS: ${message}`);
    passed++;
  } else {
    console.error(`  ❌ FAIL: ${message}`);
    failed++;
  }
}

async function runTimestampAndPaymentTests() {
  console.log('🧪 ========================================================');
  console.log('🧪 BookNest Payment Timestamps & Checkout Verification Suite');
  console.log(`🧪 Using Isolated Test Database: ${process.env.DB_PATH}`);
  console.log('🧪 ========================================================\n');

  await new Promise((resolve) => {
    server = app.listen(TEST_PORT, () => {
      console.log(`Payment Test API server running on port ${TEST_PORT}`);
      resolve();
    });
  });

  try {
    // 1. Authenticate student user
    console.log('--- 1. Authenticate Demo Student ---');
    const loginRes = await fetch(`${API_URL}/auth/login`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ email: 'user@booknest.com', password: 'User@123' })
    });
    const loginData = await loginRes.json();
    assert(loginRes.status === 200 && Boolean(loginData.token), 'Student logged in successfully and obtained token');
    const token = loginData.token;

    // 2. Fetch a book with positive stock
    const booksRes = await fetch(`${API_URL}/books`);
    const booksData = await booksRes.json();
    const availableBook = booksData.books.find((b) => b.stock > 0);
    assert(Boolean(availableBook), `Found available in-stock book for test: "${availableBook.title}" (Stock: ${availableBook.stock})`);

    // 3. Test Demo Card Payment: server-generated UTC paid_at timestamp
    console.log('\n--- 2. Test Demo Card Payment & UTC Timestamp Generation ---');
    const beforeOrderTime = new Date().toISOString();
    const cardOrderRes = await fetch(`${API_URL}/orders`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${token}`,
        'Idempotency-Key': `test-card-${Date.now()}`
      },
      body: JSON.stringify({
        address: {
          fullName: 'Aditya Chauhan',
          phone: '9876543210',
          hostelBlock: 'Aryabhata Hall',
          roomNo: 'Room 314'
        },
        paymentMethod: 'CARD',
        items: [{ bookId: availableBook.id, quantity: 1 }]
      })
    });
    const cardOrderData = await cardOrderRes.json();
    const afterOrderTime = new Date().toISOString();

    assert(cardOrderRes.status === 201, 'Card order created successfully (HTTP 201)');
    assert(cardOrderData.order.paymentStatus === 'DEMO PAID', `Card order marked 'DEMO PAID' (Got: ${cardOrderData.order.paymentStatus})`);
    assert(Boolean(cardOrderData.order.paidAt), `Server generated paidAt timestamp: ${cardOrderData.order.paidAt}`);
    
    // Verify paidAt is an ISO 8601 UTC timestamp and falls within actual execution window
    const paidAtDate = new Date(cardOrderData.order.paidAt);
    assert(!isNaN(paidAtDate.getTime()), 'paidAt is a valid ISO 8601 date string');
    assert(
      paidAtDate.getTime() >= new Date(beforeOrderTime).getTime() - 2000 &&
      paidAtDate.getTime() <= new Date(afterOrderTime).getTime() + 2000,
      'paidAt timestamp was generated by authoritative server clock at confirmation time'
    );

    // Verify formatOrderDate outputs Indian timezone (IST / Asia/Kolkata)
    const formattedIstDate = formatOrderDate(cardOrderData.order.paidAt);
    console.log(`  ℹ️ Server paidAt: ${cardOrderData.order.paidAt} -> Formatted IST: "${formattedIstDate}"`);
    assert(typeof formattedIstDate === 'string' && formattedIstDate.length > 0, 'Formatted IST date string is non-empty');
    assert(cardOrderData.order.date === formattedIstDate, 'Order response date matches server IST formatting');

    // 4. Test Timestamp Persistence in Database (Surviving Refresh)
    console.log('\n--- 3. Database Persistence & Page Refresh Simulation ---');
    const persistedOrderRow = db.prepare('SELECT * FROM orders WHERE id = ?').get(cardOrderData.order.id);
    assert(Boolean(persistedOrderRow), 'Order row exists in SQLite database');
    assert(persistedOrderRow.paid_at === cardOrderData.order.paidAt, 'persisted paid_at in SQLite matches server-generated timestamp');

    // Verify payments ledger table record
    const paymentLedgerRow = db.prepare('SELECT * FROM payments WHERE order_id = ?').get(cardOrderData.order.id);
    assert(Boolean(paymentLedgerRow), 'Entry recorded in payments ledger table');
    assert(paymentLedgerRow.status === 'DEMO PAID', 'Payments ledger records status DEMO PAID');
    assert(paymentLedgerRow.paid_at === cardOrderData.order.paidAt, 'Payments ledger records exact UTC paid_at');

    // Fetch order via GET /api/orders (simulating user refreshing order history page)
    const getOrdersRes = await fetch(`${API_URL}/orders`, {
      headers: { 'Authorization': `Bearer ${token}` }
    });
    const getOrdersData = await getOrdersRes.json();
    const fetchedOrder = getOrdersData.orders.find((o) => o.id === cardOrderData.order.id);
    assert(Boolean(fetchedOrder), 'Order retrieved via GET /api/orders after simulated page refresh');
    assert(fetchedOrder.paidAt === cardOrderData.order.paidAt, 'paidAt survives page refresh intact and unchanged');
    assert(fetchedOrder.date === formattedIstDate, 'date in order history remains formatted in IST after page refresh');

    // 5. Test Cash on Delivery (COD): paymentStatus = PENDING (COD), paidAt = null
    console.log('\n--- 4. Test Cash on Delivery (COD) Does NOT Fabricate Payment ---');
    const codOrderRes = await fetch(`${API_URL}/orders`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${token}`,
        'Idempotency-Key': `test-cod-${Date.now()}`
      },
      body: JSON.stringify({
        address: {
          fullName: 'Aditya Chauhan',
          phone: '9876543210',
          hostelBlock: 'Aryabhata Hall',
          roomNo: 'Room 314'
        },
        paymentMethod: 'COD',
        items: [{ bookId: availableBook.id, quantity: 1 }]
      })
    });
    const codOrderData = await codOrderRes.json();
    assert(codOrderRes.status === 201, 'COD order created successfully (HTTP 201)');
    assert(codOrderData.order.paymentStatus === 'PENDING (COD)', `COD paymentStatus is honest 'PENDING (COD)' (Got: ${codOrderData.order.paymentStatus})`);
    assert(codOrderData.order.paidAt === null, `COD order paidAt is null (no fake payment timestamp)`);

    const codOrderRow = db.prepare('SELECT * FROM orders WHERE id = ?').get(codOrderData.order.id);
    assert(codOrderRow.paid_at === null, 'SQLite database paid_at is NULL for COD order');

    // 6. Test Student Order Cancellation records cancelled_at
    console.log('\n--- 5. Test Student Order Cancellation & cancelled_at Timestamp ---');
    const cancelRes = await fetch(`${API_URL}/orders/${cardOrderData.order.id}/cancel`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${token}`
      }
    });
    const cancelData = await cancelRes.json();
    assert(cancelRes.status === 200 && cancelData.success === true, 'Student order cancelled successfully');
    
    const cancelledRow = db.prepare('SELECT status, cancelled_at FROM orders WHERE id = ?').get(cardOrderData.order.id);
    assert(cancelledRow.status === 'Cancelled', 'Order status updated to Cancelled');
    assert(Boolean(cancelledRow.cancelled_at), `cancelled_at timestamp recorded: ${cancelledRow.cancelled_at}`);

    // 7. Test CORS OPTIONS Preflight Request (Production 401 bug fix verification)
    console.log('\n--- 6. Test CORS OPTIONS Preflight Interception (401 Fix) ---');
    const preflightRes = await fetch(`${API_URL}/orders`, {
      method: 'OPTIONS',
      headers: {
        'Origin': 'https://booknest-api-tnwu.onrender.com',
        'Access-Control-Request-Method': 'POST',
        'Access-Control-Request-Headers': 'content-type,authorization,idempotency-key'
      }
    });
    assert(
      preflightRes.status === 204 || preflightRes.status === 200,
      `CORS OPTIONS preflight returns HTTP 204/200 without 401 auth rejection (Status: ${preflightRes.status})`
    );
    const allowOrigin = preflightRes.headers.get('access-control-allow-origin');
    assert(
      allowOrigin === 'https://booknest-api-tnwu.onrender.com',
      `Access-Control-Allow-Origin header returned correctly for production domain (Got: ${allowOrigin})`
    );

    console.log('\n========================================================');
    console.log(`Payment & Timestamp Test Results: ${passed} Passed, ${failed} Failed`);
    console.log('========================================================\n');

  } catch (err) {
    console.error('Test execution error:', err);
    failed++;
  } finally {
    if (server) {
      server.close();
    }
    if (closeDatabase) {
      closeDatabase();
    }
  }

  process.exit(failed > 0 ? 1 : 0);
}

runTimestampAndPaymentTests();
